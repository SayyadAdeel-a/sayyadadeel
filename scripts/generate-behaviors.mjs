// Generate the site-wide behaviour bible from the decoded IX payloads: which
// interactions each route carries, what triggers them, and which widgets it has.
//
// Usage: node scripts/generate-behaviors.mjs
import fs from "node:fs";
import path from "node:path";
import { ART_ROOT, allRoutes, readPage } from "./lib/page-pipeline.mjs";

const CONTROL_LABEL = {
  standard: "restart (default)",
  restart: "restart",
  play: "play",
  reverse: "reverse",
  reverseFlipEase: "reverse + flipped ease",
  pause: "pause",
  resume: "resume",
  togglePlayReverse: "toggle play/reverse",
  togglePlayReverseFlipEase: "toggle play/reverse + flipped ease",
  stop: "stop",
  none: "none",
  scroll: "on enter",
  load: "on load",
  continuous: "continuous",
};

const TARGET_LABEL = (target) => {
  const [kind, value, meta] = target;
  const selector = Array.isArray(value)
    ? kind === "wf:inst" || kind === "wf:id"
      ? `#${value.join(", #")}`
      : value.join("")
    : String(value);
  const scope = meta?.relationship && meta.relationship !== "none"
    ? ` ${meta.relationship} trigger`
    : "";
  return `${selector}${scope}`;
};

const CHANNELS = new Map();
const summariseActions = (timeline) => {
  const parts = [];
  for (const action of timeline.actions ?? []) {
    const props = action.properties?.["wf:transform"] ?? {};
    for (const channel of Object.keys(props)) {
      CHANNELS.set(channel, (CHANNELS.get(channel) ?? 0) + 1);
      const pair = props[channel];
      const label = Array.isArray(pair)
        ? `${channel}: ${JSON.stringify(pair[0])} -> ${JSON.stringify(pair[1])}`
        : `${channel}: ${JSON.stringify(pair)}`;
      if (!parts.includes(label)) parts.push(label);
    }
  }
  return parts.join("; ");
};

const byPage = new Map();

for (const entry of allRoutes()) {
  const { body } = readPage(entry.pageKey);
  const ix = JSON.parse(
    fs.readFileSync(path.join(ART_ROOT, entry.pageKey, "webflow-ix2.json"), "utf8")
  );
  const byId = new Map(ix.timelines.map((t) => [t.id, t]));

  const rows = [];
  for (const interaction of ix.interactions) {
    const triggers = (interaction.triggers ?? []).map(([name, config, target]) => {
      const control = CONTROL_LABEL[config.control ?? config.controlType] ?? "-";
      const where = target ? TARGET_LABEL(target) : "page";
      const extra = [];
      if (config.scrollTriggerConfig) {
        const st = config.scrollTriggerConfig;
        extra.push(`start "${st.start}"`);
        if (st.scrub !== null && st.scrub !== undefined) {
          extra.push(`scrub ${st.scrub}`);
        }
      }
      if (config.pluginConfig?.restingState) {
        const rest = config.pluginConfig.restingState;
        extra.push(`resting ${rest.x ?? 50}%/${rest.y ?? 50}%`);
      }
      return `\`${name}\` on \`${where}\` (${control}${
        extra.length ? `, ${extra.join(", ")}` : ""
      })`;
    });

    const effects = [];
    for (const id of interaction.timelineIds ?? []) {
      const timeline = byId.get(id);
      if (!timeline) continue;
      const summary = summariseActions(timeline);
      const loop = timeline.settings?.repeat
        ? ` (looped x${timeline.settings.repeat === -1 ? "inf" : timeline.settings.repeat})`
        : "";
      effects.push(`${summary}${loop}`);
    }

    rows.push({ interaction, triggers, effects });
  }

  byPage.set(entry.route, { rows, body });
}

const lines = [];
lines.push("# Behaviour bible");
lines.push("");
lines.push("Generated by `scripts/generate-behaviors.mjs` from the decoded IX");
lines.push("payloads. The engine semantics behind every entry are documented in");
lines.push("`IX3-ENGINE.md`; this file is the inventory.");
lines.push("");

lines.push("## Transform channels in use across the site");
lines.push("");
lines.push("| Channel | Actions |");
lines.push("| --- | ---: |");
for (const [channel, count] of [...CHANNELS].sort((a, b) => b[1] - a[1])) {
  lines.push(`| \`${channel}\` | ${count} |`);
}
lines.push("");

// Group the interactions that every page shares.
const shared = new Map();
for (const [route, { rows }] of byPage) {
  if (route === "/") continue;
  for (const row of rows) {
    const key = row.triggers.join(" | ") + " :: " + row.effects.join(" | ");
    if (!shared.has(key)) shared.set(key, { count: 0, example: row });
    shared.get(key).count += 1;
  }
}

lines.push("## Interactions present on every generated page");
lines.push("");
lines.push(
  "All 24 generated pages carry the same interaction set apart from their own"
);
lines.push("content hooks, so these entries are implemented once by");
lines.push("`src/components/sites/relab-0c02b053/shared/ix/runtime.ts`.");
lines.push("");
lines.push("| Trigger | What it animates | Pages |");
lines.push("| --- | --- | ---: |");
const sharedRows = [...shared.values()].sort((a, b) => b.count - a.count);
for (const { count, example } of sharedRows) {
  if (count < 20) continue;
  lines.push(
    `| ${example.triggers.join("<br>")} | ${example.effects.join("<br>") || "—"} | ${count} |`
  );
}
lines.push("");

lines.push("## Per-route inventory");
lines.push("");
for (const [route, { rows }] of byPage) {
  lines.push(`### \`${route}\``);
  lines.push("");
  lines.push("| Interaction | Trigger | Animates |");
  lines.push("| --- | --- | --- |");
  for (const row of rows) {
    lines.push(
      `| \`${row.interaction.id}\` | ${row.triggers.join("<br>")} | ${
        row.effects.join("<br>") || "—"
      } |`
    );
  }
  lines.push("");
}

fs.writeFileSync(`${ART_ROOT}/BEHAVIORS.md`, lines.join("\n"));
console.log(
  `wrote ${ART_ROOT}/BEHAVIORS.md (${byPage.size} routes, ${CHANNELS.size} channels)`
);