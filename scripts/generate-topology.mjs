// Generate the site-wide page topology: for every cloned route, its section
// order, the components it maps to, its interaction/timeline counts and its
// widget inventory.
//
// Usage: node scripts/generate-topology.mjs
import fs from "node:fs";
import path from "node:path";
import { ART_ROOT, SITE_KEY, allRoutes, readPage } from "./lib/page-pipeline.mjs";

const SHELL = {
  "header-section": "SiteHeader",
  "cta-section": "SiteCta",
  "footer-section": "SiteFooter",
  "template-buttons-wrapper": "SiteTemplateButtons",
};

function componentName(cls) {
  const cleaned = cls
    .replace(/^w-node-/, "")
    .replace(/[^a-zA-Z0-9]+(.)/g, (_, c) => c.toUpperCase())
    .replace(/[^a-zA-Z0-9]/g, "");
  const name = /Section$/.test(cleaned) ? cleaned : `${cleaned}Section`;
  return name.charAt(0).toUpperCase() + name.slice(1);
}

const rows = [];
for (const entry of allRoutes()) {
  const { body } = readPage(entry.pageKey);
  const ix = JSON.parse(
    fs.readFileSync(path.join(ART_ROOT, entry.pageKey, "webflow-ix2.json"), "utf8")
  );

  const sections = [];
  const classes = new Set();
  for (const m of body.matchAll(/class="([^"]*)"/g)) {
    for (const c of m[1].split(/\s+/)) classes.add(c);
  }

  const sectionPattern =
    /<section\b[^>]*class="([^"]*)"|<div\b[^>]*class="([^"]*)"\s*data-wf-component-id[^>]*>/g;
  // Reuse the same top-level split the converter uses.
  const { parseFragment, primaryClass } = await import("./lib/page-pipeline.mjs");
  for (const node of parseFragment(body)) {
    if (node.type !== "el") continue;
    if (node.tag === "script" || node.tag === "noscript") continue;
    const cls = primaryClass(node);
    sections.push({
      cls,
      component: SHELL[cls] ?? componentName(cls),
      shared: Boolean(SHELL[cls]),
    });
  }

  rows.push({
    route: entry.route,
    pageKey: entry.pageKey,
    title: entry.title,
    sections,
    interactions: ix.interactions.length,
    timelines: ix.timelines.length,
    widgets: {
      "w-slider": classes.has("w-slider"),
      "w-tabs": classes.has("w-tabs"),
      "w-form": classes.has("w-form"),
      "w-background-video": classes.has("w-background-video"),
      "menu-button": classes.has("menu-button"),
      "faq-toggle": classes.has("faq-toggle"),
      "accordion": classes.has("accordion-item"),
      "hero-intro-tabs":
        classes.has("hero-intro-card-box") && classes.has("single-image-wrap"),
    },
  });
}

const lines = [];
lines.push("# Page topology");
lines.push("");
lines.push(
  "Generated by `scripts/generate-topology.mjs`. Every published route of the"
);
lines.push(
  " reference, its top-level sections in document order, and the interaction"
);
lines.push(" payload each one carries.");
lines.push("");
lines.push(
  "`SiteHeader`, `SiteCta` and `SiteFooter` are shared components: the shell"
);
lines.push(
  " Webflow repeats on every page differs only by which anchors it marked"
);
lines.push(
  " `aria-current=\"page\"`, so they are emitted once and take a `currentPath`"
);
lines.push(" prop.");
lines.push("");

lines.push("## Summary");
lines.push("");
lines.push(
  "| Route | Sections | Interactions | Timelines | Slider | Tabs | Form | Menu | FAQ |"
);
lines.push("| --- | ---: | ---: | ---: | :-: | :-: | :-: | :-: | :-: |");
for (const row of rows) {
  const w = row.widgets;
  lines.push(
    `| \`${row.route}\` | ${row.sections.length} | ${row.interactions} | ${row.timelines} |` +
      ` ${w["w-slider"] ? "•" : ""} | ${w["w-tabs"] ? "•" : ""} | ${w["w-form"] ? "•" : ""} |` +
      ` ${w["menu-button"] ? "•" : ""} | ${w["faq-toggle"] || w.accordion ? "•" : ""} |`
  );
}
lines.push("");

for (const row of rows) {
  lines.push(`## \`${row.route}\``);
  lines.push("");
  lines.push(`- Page key: \`${row.pageKey}\``);
  lines.push(`- Title: ${row.title ?? "(none)"}`);
  lines.push(
    `- IX payload: ${row.interactions} interactions, ${row.timelines} timelines`
  );
  lines.push("- Sections, in document order:");
  lines.push("");
  for (const section of row.sections) {
    const badge = section.shared ? " *(shared)*" : "";
    lines.push(`  - \`${section.cls}\` → \`${section.component}\`${badge}`);
  }
  lines.push("");
}

fs.mkdirSync(`${ART_ROOT}/generated`, { recursive: true });
const out = `${ART_ROOT}/PAGE_TOPOLOGY.md`;
fs.writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out} (${rows.length} routes)`);

// Also record the same data as JSON for other tooling.
fs.writeFileSync(
  `${ART_ROOT}/generated/topology.json`,
  JSON.stringify(rows, null, 2)
);
console.log(`wrote ${ART_ROOT}/generated/topology.json`);
void SITE_KEY;